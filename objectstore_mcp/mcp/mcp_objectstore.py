"""Typed MCP tools over the object-store backends (CONN-OBJECTSTORE-MCP-R005, R006).

One tool per operation, no ``action`` routing. The per-operation tools for the
backend protocol itself (``objectstore_list_buckets``, ``objectstore_put_object``,
``objectstore_presigned_url`` ...) are generated by the SDK from
``ObjectStoreBackend`` and act on the default store. This module adds the
operations the protocol does not carry:

* store discovery (``objectstore_list_stores``);
* composite object operations the tool layer guards (move, prefix delete with a
  dry run, file and directory transfers), each size- and count-capped
  (CONCEPT:OB-OS.safety.size-caps-list-batch);
* S3 bucket and object management (lifecycle rules, versioning, object tags),
  which reach the S3 client of an ``s3`` store and refuse with
  ``STORAGE_UNSUPPORTED`` on any other backend;
* knowledge-graph ingestion of bucket and object metadata.

Every tool takes an optional ``store`` naming a store from ``OBJECTSTORE_STORES``.
Backends stay pure storage adapters; safety policy lives here only.
"""

from pathlib import Path
from typing import Any, Literal

from fastmcp import Context, FastMCP
from pydantic import BaseModel, Field
from scion_sdk.mcp.destructive import guard_destructive
from scion_sdk.storage import StorageError, UnsupportedOperationError

from objectstore_mcp.auth import entitled_store_names, get_backend
from objectstore_mcp.config import load_limits, load_stores

_FORBIDDEN_KEY_CHARS = ("*", "?")

StoreArg = Field(
    default=None,
    description=(
        "Named store from OBJECTSTORE_STORES (default: the configured default "
        "store; 'local' is always available). See objectstore_list_stores."
    ),
)


class LifecycleRule(BaseModel):
    """One bucket lifecycle rule (S3 ``LifecycleConfiguration.Rules`` entry)."""

    id: str = Field(description="Rule identifier, unique within the bucket.")
    prefix: str = Field(default="", description="Key prefix the rule applies to.")
    enabled: bool = Field(default=True, description="Rule status Enabled/Disabled.")
    expiration_days: int | None = Field(
        default=None, ge=1, description="Delete current objects this many days old."
    )
    noncurrent_expiration_days: int | None = Field(
        default=None,
        ge=1,
        description="Delete noncurrent versions this many days after they go stale.",
    )
    abort_incomplete_multipart_days: int | None = Field(
        default=None, ge=1, description="Abort unfinished multipart uploads."
    )
    transition_days: int | None = Field(
        default=None, ge=0, description="Move objects to storage_class after N days."
    )
    storage_class: str | None = Field(
        default=None, description="Target storage class for transition_days."
    )


def _require_dest(dst_key: str) -> None:
    if not dst_key:
        raise ValueError("dst_key is required.")


def _single_key(bucket: str, key: str, operation: str) -> None:
    if not bucket or not key:
        raise ValueError(f"{operation} requires an explicit bucket and key.")
    if any(ch in key for ch in _FORBIDDEN_KEY_CHARS):
        raise ValueError(
            f"{operation} targets exactly one object; wildcard characters are "
            f"not allowed in key {key!r}."
        )


async def _confirmed(
    ctx: Context | None, operation: str, arguments: dict[str, Any], confirm: bool
) -> dict[str, Any] | Any | None:
    """The SDK destructive guard: ``None`` to proceed, else the result to return."""
    return await guard_destructive(ctx, operation, arguments, confirm=confirm)


def _s3_client(store: str | None) -> tuple[Any, str]:
    """The boto3 client of an ``s3`` store; other backends refuse."""
    backend, config = get_backend(store)
    backend = getattr(backend, "inner", backend)
    if getattr(backend, "backend_type", "") != "s3" or not hasattr(backend, "client"):
        raise UnsupportedOperationError(
            f"store {config.name!r} ({config.backend}) does not support this "
            "S3 bucket-management operation"
        )
    return backend.client, config.name


def _client_error_code(exc: Exception) -> str:
    response = getattr(exc, "response", None) or {}
    return str((response.get("Error") or {}).get("Code") or "")


def _s3_call(operation: str, call: Any, absent: tuple[str, ...] = ()) -> Any:
    """Run one S3 call; an ``absent`` error code answers ``None``."""
    try:
        return call()
    except Exception as exc:
        code = _client_error_code(exc)
        if code and code in absent:
            return None
        if code in {"NoSuchBucket", "NoSuchKey", "404", "NotFound"}:
            from scion_sdk.storage import NotFoundError

            raise NotFoundError(f"{operation}: not found ({code})") from exc
        raise StorageError(
            f"{operation} failed ({code or type(exc).__name__})"
        ) from exc


def _rule_to_s3(rule: LifecycleRule) -> dict[str, Any]:
    body: dict[str, Any] = {
        "ID": rule.id,
        "Filter": {"Prefix": rule.prefix},
        "Status": "Enabled" if rule.enabled else "Disabled",
    }
    if rule.expiration_days is not None:
        body["Expiration"] = {"Days": rule.expiration_days}
    if rule.noncurrent_expiration_days is not None:
        body["NoncurrentVersionExpiration"] = {
            "NoncurrentDays": rule.noncurrent_expiration_days
        }
    if rule.abort_incomplete_multipart_days is not None:
        body["AbortIncompleteMultipartUpload"] = {
            "DaysAfterInitiation": rule.abort_incomplete_multipart_days
        }
    if rule.transition_days is not None:
        if not rule.storage_class:
            raise ValueError(f"rule {rule.id!r}: transition_days needs storage_class.")
        body["Transitions"] = [
            {"Days": rule.transition_days, "StorageClass": rule.storage_class}
        ]
    if len(body) == 3:
        raise ValueError(f"rule {rule.id!r} sets no action (expiration/transition).")
    return body


def _rule_from_s3(raw: dict[str, Any]) -> dict[str, Any]:
    filt = raw.get("Filter") or {}
    transitions = raw.get("Transitions") or [{}]
    return {
        "id": raw.get("ID", ""),
        "prefix": filt.get("Prefix", raw.get("Prefix", "")),
        "enabled": raw.get("Status") == "Enabled",
        "expiration_days": (raw.get("Expiration") or {}).get("Days"),
        "noncurrent_expiration_days": (
            raw.get("NoncurrentVersionExpiration") or {}
        ).get("NoncurrentDays"),
        "abort_incomplete_multipart_days": (
            raw.get("AbortIncompleteMultipartUpload") or {}
        ).get("DaysAfterInitiation"),
        "transition_days": transitions[0].get("Days"),
        "storage_class": transitions[0].get("StorageClass"),
    }


def register_objectstore_tools(mcp: FastMCP) -> None:
    """Register the typed store, transfer, S3-management and ingest tools."""

    # --- stores -----------------------------------------------------------

    @mcp.tool(tags={"buckets"}, annotations={"readOnlyHint": True})
    async def objectstore_list_stores() -> dict[str, Any]:
        """List the named stores the caller is entitled to, with backend and endpoint."""
        stores = load_stores()
        entitled = set(entitled_store_names(list(stores)))
        return {
            name: {
                "backend": cfg.backend,
                "bucket": cfg.bucket,
                "endpoint": cfg.endpoint,
            }
            for name, cfg in sorted(stores.items())
            if name in entitled
        }

    # --- composite object operations --------------------------------------

    @mcp.tool(tags={"objects"}, annotations={"destructiveHint": True})
    async def objectstore_move_object(
        src_bucket: str,
        src_key: str,
        dst_bucket: str,
        dst_key: str,
        store: str | None = StoreArg,
        confirm: bool = False,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        """Move one object: copy it to dst_bucket/dst_key, then delete the source."""
        _require_dest(dst_key)
        _single_key(src_bucket, src_key, "move")
        if (
            refused := await _confirmed(
                ctx,
                "objectstore_move_object",
                {"src_bucket": src_bucket, "src_key": src_key, "dst_bucket": dst_bucket, "dst_key": dst_key},
                confirm,
            )
        ) is not None:
            return refused
        backend, _config = get_backend(store)
        info = backend.copy_object(src_bucket, src_key, dst_bucket, dst_key)
        backend.delete_object(src_bucket, src_key)
        return {
            "source": {"bucket": src_bucket, "key": src_key},
            "dest": {"bucket": dst_bucket, **info.to_dict()},
        }

    @mcp.tool(tags={"objects"}, annotations={"destructiveHint": True})
    async def objectstore_delete_objects_by_prefix(
        bucket: str,
        prefix: str,
        max_keys: int | None = Field(
            default=None, description="Cap (bounded by OBJECTSTORE_MAX_BATCH_KEYS)."
        ),
        dry_run: bool = Field(
            default=True, description="List what would be deleted; delete nothing."
        ),
        store: str | None = StoreArg,
        confirm: bool = False,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        """Delete objects under a non-empty prefix (dry run by default, count-capped)."""
        if not bucket or not prefix:
            raise ValueError(
                "An explicit bucket and a non-empty prefix are required "
                "(refusing to bulk-delete a whole bucket)."
            )
        if not dry_run and (
            refused := await _confirmed(
                ctx,
                "objectstore_delete_objects_by_prefix",
                {"bucket": bucket, "prefix": prefix, "max_keys": max_keys},
                confirm,
            )
        ) is not None:
            return refused
        limits = load_limits()
        cap = min(max_keys or limits.max_batch_keys, limits.max_batch_keys)
        backend, _config = get_backend(store)
        page = backend.list_objects(bucket, prefix=prefix, max_keys=cap)
        keys = [obj.key for obj in page.objects]
        if not dry_run:
            for key in keys:
                backend.delete_object(bucket, key)
        return {
            "bucket": bucket,
            "prefix": prefix,
            "dry_run": dry_run,
            "matched": len(keys),
            "keys": keys,
            "deleted": 0 if dry_run else len(keys),
            "truncated": page.truncated,
        }

    # --- transfers --------------------------------------------------------

    @mcp.tool(tags={"transfer"})
    async def objectstore_upload_file(
        bucket: str,
        local_path: str,
        key: str | None = Field(default=None, description="Default: the file name."),
        content_type: str | None = None,
        metadata: dict[str, str] | None = None,
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Upload one local file to an object (capped by OBJECTSTORE_MAX_TRANSFER_BYTES)."""
        limits = load_limits()
        local = Path(local_path).expanduser()
        if not local.is_file():
            raise ValueError(f"local_path {str(local)!r} is not a file.")
        size = local.stat().st_size
        if size > limits.max_transfer_bytes:
            raise ValueError(
                f"File is {size} bytes, over the {limits.max_transfer_bytes}-byte "
                "transfer cap (OBJECTSTORE_MAX_TRANSFER_BYTES)."
            )
        backend, _config = get_backend(store)
        info = backend.put_object(
            bucket,
            key or local.name,
            local.read_bytes(),
            content_type=content_type,
            metadata=metadata,
        )
        return {"bucket": bucket, "uploaded": str(local), **info.to_dict()}

    @mcp.tool(tags={"transfer"})
    async def objectstore_download_file(
        bucket: str,
        key: str,
        local_path: str,
        overwrite: bool = False,
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Download one object to a local file (capped by OBJECTSTORE_MAX_TRANSFER_BYTES)."""
        limits = load_limits()
        local = Path(local_path).expanduser()
        if local.exists() and not overwrite:
            raise ValueError(f"local_path {str(local)!r} exists; pass overwrite=true.")
        backend, _config = get_backend(store)
        data = backend.get_object(bucket, key, max_bytes=limits.max_transfer_bytes)
        local.parent.mkdir(parents=True, exist_ok=True)
        local.write_bytes(data)
        return {
            "bucket": bucket,
            "key": key,
            "local_path": str(local),
            "size": len(data),
        }

    @mcp.tool(tags={"transfer"})
    async def objectstore_upload_directory(
        bucket: str,
        local_dir: str,
        prefix: str = "",
        max_keys: int | None = Field(
            default=None, description="Cap (bounded by OBJECTSTORE_MAX_BATCH_KEYS)."
        ),
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Upload every file under a local directory to objects under a prefix (capped)."""
        limits = load_limits()
        root = Path(local_dir).expanduser()
        if not root.is_dir():
            raise ValueError("Configured local path is not a directory.")
        cap = min(max_keys or limits.max_batch_keys, limits.max_batch_keys)
        files = sorted(f for f in root.rglob("*") if f.is_file())
        if len(files) > cap:
            raise ValueError(
                f"Directory holds {len(files)} files, over the {cap}-key batch cap; "
                "raise max_keys (bounded by OBJECTSTORE_MAX_BATCH_KEYS) or narrow it."
            )
        total = sum(f.stat().st_size for f in files)
        if total > limits.max_transfer_bytes:
            raise ValueError(
                f"Directory totals {total} bytes, over the "
                f"{limits.max_transfer_bytes}-byte transfer cap."
            )
        backend, _config = get_backend(store)
        uploaded = []
        for path in files:
            key = prefix + path.relative_to(root).as_posix()
            backend.put_object(bucket, key, path.read_bytes())
            uploaded.append(key)
        return {"bucket": bucket, "uploaded": uploaded, "count": len(uploaded)}

    @mcp.tool(tags={"transfer"})
    async def objectstore_download_prefix(
        bucket: str,
        local_dir: str,
        prefix: str = "",
        max_keys: int | None = Field(
            default=None, description="Cap (bounded by OBJECTSTORE_MAX_BATCH_KEYS)."
        ),
        overwrite: bool = False,
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Download the objects under a prefix into a local directory (capped)."""
        limits = load_limits()
        cap = min(max_keys or limits.max_batch_keys, limits.max_batch_keys)
        backend, _config = get_backend(store)
        page = backend.list_objects(bucket, prefix=prefix, max_keys=cap)
        total = sum(obj.size for obj in page.objects)
        if total > limits.max_transfer_bytes:
            raise ValueError(
                f"Prefix totals {total} bytes, over the "
                f"{limits.max_transfer_bytes}-byte transfer cap."
            )
        root = Path(local_dir).expanduser()
        downloaded = []
        for obj in page.objects:
            relative = obj.key[len(prefix) :] if prefix else obj.key
            target = root / relative.lstrip("/")
            if target.exists() and not overwrite:
                raise ValueError(f"{str(target)!r} exists; pass overwrite=true.")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(
                backend.get_object(bucket, obj.key, max_bytes=limits.max_transfer_bytes)
            )
            downloaded.append({"key": obj.key, "local_path": str(target)})
        return {
            "bucket": bucket,
            "prefix": prefix,
            "count": len(downloaded),
            "downloaded": downloaded,
            "truncated": page.truncated,
        }

    # --- S3 bucket management: lifecycle ----------------------------------

    @mcp.tool(tags={"lifecycle"}, annotations={"readOnlyHint": True})
    async def objectstore_get_bucket_lifecycle(
        bucket: str, store: str | None = StoreArg
    ) -> dict[str, Any]:
        """Read a bucket's lifecycle rules (empty list when none are set)."""
        client, name = _s3_client(store)
        raw = _s3_call(
            "get_bucket_lifecycle",
            lambda: client.get_bucket_lifecycle_configuration(Bucket=bucket),
            absent=("NoSuchLifecycleConfiguration",),
        )
        rules = [_rule_from_s3(r) for r in (raw or {}).get("Rules", [])]
        return {"store": name, "bucket": bucket, "rules": rules}

    @mcp.tool(tags={"lifecycle"}, annotations={"idempotentHint": True})
    async def objectstore_put_bucket_lifecycle(
        bucket: str,
        rules: list[LifecycleRule],
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Replace a bucket's lifecycle rules (expiry, noncurrent expiry, transitions)."""
        if not rules:
            raise ValueError(
                "rules is empty; use objectstore_delete_bucket_lifecycle to clear."
            )
        client, name = _s3_client(store)
        body = {"Rules": [_rule_to_s3(rule) for rule in rules]}
        _s3_call(
            "put_bucket_lifecycle",
            lambda: client.put_bucket_lifecycle_configuration(
                Bucket=bucket, LifecycleConfiguration=body
            ),
        )
        return {"store": name, "bucket": bucket, "rules": len(rules)}

    @mcp.tool(tags={"lifecycle"}, annotations={"destructiveHint": True})
    async def objectstore_delete_bucket_lifecycle(
        bucket: str,
        store: str | None = StoreArg,
        confirm: bool = False,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        """Remove every lifecycle rule from a bucket."""
        if (
            refused := await _confirmed(
                ctx, "objectstore_delete_bucket_lifecycle", {"bucket": bucket}, confirm
            )
        ) is not None:
            return refused
        client, name = _s3_client(store)
        _s3_call(
            "delete_bucket_lifecycle",
            lambda: client.delete_bucket_lifecycle(Bucket=bucket),
        )
        return {"store": name, "bucket": bucket, "deleted": True}

    # --- S3 bucket management: versioning ---------------------------------

    @mcp.tool(tags={"lifecycle"}, annotations={"readOnlyHint": True})
    async def objectstore_get_bucket_versioning(
        bucket: str, store: str | None = StoreArg
    ) -> dict[str, Any]:
        """Read a bucket's versioning state (Enabled, Suspended or unset)."""
        client, name = _s3_client(store)
        raw = _s3_call(
            "get_bucket_versioning",
            lambda: client.get_bucket_versioning(Bucket=bucket),
        )
        return {"store": name, "bucket": bucket, "status": (raw or {}).get("Status")}

    @mcp.tool(tags={"lifecycle"}, annotations={"idempotentHint": True})
    async def objectstore_put_bucket_versioning(
        bucket: str,
        status: Literal["Enabled", "Suspended"],
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Enable or suspend object versioning on a bucket."""
        client, name = _s3_client(store)
        _s3_call(
            "put_bucket_versioning",
            lambda: client.put_bucket_versioning(
                Bucket=bucket, VersioningConfiguration={"Status": status}
            ),
        )
        return {"store": name, "bucket": bucket, "status": status}

    # --- S3 object tags ---------------------------------------------------

    @mcp.tool(tags={"objects"}, annotations={"readOnlyHint": True})
    async def objectstore_get_object_tags(
        bucket: str, key: str, store: str | None = StoreArg
    ) -> dict[str, Any]:
        """Read an object's tag set."""
        client, name = _s3_client(store)
        raw = _s3_call(
            "get_object_tags",
            lambda: client.get_object_tagging(Bucket=bucket, Key=key),
            absent=("NoSuchTagSet",),
        )
        tags = {t["Key"]: t["Value"] for t in (raw or {}).get("TagSet", [])}
        return {"store": name, "bucket": bucket, "key": key, "tags": tags}

    @mcp.tool(tags={"objects"}, annotations={"idempotentHint": True})
    async def objectstore_put_object_tags(
        bucket: str,
        key: str,
        tags: dict[str, str],
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Replace an object's tag set (at most 10 tags)."""
        if len(tags) > 10:
            raise ValueError("An object holds at most 10 tags.")
        client, name = _s3_client(store)
        tag_set = [{"Key": k, "Value": v} for k, v in sorted(tags.items())]
        _s3_call(
            "put_object_tags",
            lambda: client.put_object_tagging(
                Bucket=bucket, Key=key, Tagging={"TagSet": tag_set}
            ),
        )
        return {"store": name, "bucket": bucket, "key": key, "tags": dict(tags)}

    @mcp.tool(tags={"objects"}, annotations={"destructiveHint": True})
    async def objectstore_delete_object_tags(
        bucket: str,
        key: str,
        store: str | None = StoreArg,
        confirm: bool = False,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        """Remove every tag from an object."""
        if (
            refused := await _confirmed(
                ctx,
                "objectstore_delete_object_tags",
                {"bucket": bucket, "key": key},
                confirm,
            )
        ) is not None:
            return refused
        client, name = _s3_client(store)
        _s3_call(
            "delete_object_tags",
            lambda: client.delete_object_tagging(Bucket=bucket, Key=key),
        )
        return {"store": name, "bucket": bucket, "key": key, "deleted": True}

    # --- knowledge-graph ingestion ----------------------------------------

    @mcp.tool(tags={"objectstore", "kg"})
    async def objectstore_ingest_buckets(
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Mirror the store's buckets into the knowledge graph as :Bucket nodes.

        Metadata only; returns ``{"ingested": None}`` when no engine is reachable.
        CONCEPT:AU-KG.ingest.enterprise-source-extractor.
        """
        from objectstore_mcp.kg_ingest import ingest_buckets

        backend, config = get_backend(store)
        bucket_dicts = [b.to_dict() for b in backend.list_buckets()]
        result = await ingest_buckets(
            bucket_dicts,
            store=config.name,
            backend=config.backend,
            endpoint=config.endpoint,
        )
        return {"store": config.name, "listed": len(bucket_dicts), "ingested": result}

    @mcp.tool(tags={"objectstore", "kg"})
    async def objectstore_ingest_objects(
        bucket: str,
        prefix: str = "",
        max_keys: int | None = Field(
            default=None, description="Cap (bounded by OBJECTSTORE_MAX_LIST_KEYS)."
        ),
        store: str | None = StoreArg,
    ) -> dict[str, Any]:
        """Mirror object metadata under a prefix into the knowledge graph as :Object nodes.

        Object bytes are never copied into the graph.
        """
        from objectstore_mcp.kg_ingest import ingest_objects

        limits = load_limits()
        cap = min(max_keys or limits.max_list_keys, limits.max_list_keys)
        backend, config = get_backend(store)
        page = backend.list_objects(bucket, prefix=prefix, max_keys=cap)
        object_dicts = [o.to_dict() for o in page.objects]
        result = await ingest_objects(object_dicts, store=config.name, bucket=bucket)
        return {
            "store": config.name,
            "bucket": bucket,
            "listed": len(object_dicts),
            "truncated": page.truncated,
            "ingested": result,
        }

    # Re-exported so linters see the closures as used; FastMCP holds the refs.
    _ = (
        objectstore_list_stores,
        objectstore_move_object,
        objectstore_delete_objects_by_prefix,
        objectstore_upload_file,
        objectstore_download_file,
        objectstore_upload_directory,
        objectstore_download_prefix,
        objectstore_get_bucket_lifecycle,
        objectstore_put_bucket_lifecycle,
        objectstore_delete_bucket_lifecycle,
        objectstore_get_bucket_versioning,
        objectstore_put_bucket_versioning,
        objectstore_get_object_tags,
        objectstore_put_object_tags,
        objectstore_delete_object_tags,
        objectstore_ingest_buckets,
        objectstore_ingest_objects,
    )


